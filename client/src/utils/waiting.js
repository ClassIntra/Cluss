// 等待中的状态文案
//
// 心理学依据：不确定的等待比确定的等待难熬得多（不确定性厌恶）。
// 现在三个页面在"点了发送但还没出第一个字"时只有一个闪烁光标 ——
// 光标不说明任何事，8 秒不出字学生就会以为卡死，然后反复点或直接关掉。
//
// 三条设计约束：
//   1. **不编造进度**。「已完成 60%」这类假进度一旦被识破，信任比不给还差。
//      这里只说"还在工作"以及"为什么可能慢"。
//   2. **随时间升级信息量**，而不是原地重复同一句话。
//   3. **最后必须给出路**：等太久时告诉他能做什么（停止重试），
//      只安抚不给动作，焦虑会转成无力感。

// 阶段阈值（毫秒）。挑 8s / 20s 是因为：正常首字延迟在 1~4 秒，
// 超过 8 秒已经明显异常，20 秒则是"该做点什么了"的程度。
const STAGE_QUICK = 8000;
const STAGE_LONG = 20000;

// kind: 'chat' | 'study' | 'writing' | 'grade'
function waitingLabel(elapsedMs, kind) {
  var ms = Number(elapsedMs) || 0;

  if (ms < STAGE_QUICK) return '正在思考…';

  if (ms < STAGE_LONG) {
    // 分场景解释"为什么慢"，比笼统的"请稍等"更能降低不确定感：
    // 学生知道慢的理由，就不会怀疑是自己网络坏了
    if (kind === 'grade') return '在逐题核对，题多的时候会慢一些…';
    if (kind === 'writing') return '在组织内容，篇幅长的时候会慢一些…';
    if (kind === 'study') return '在推敲这道题，内容多的时候会慢一些…';
    return '在推敲，内容多或历史较长时会慢一些…';
  }

  // 到这里已经等了 20 秒以上：给明确的动作，而不是继续安抚
  return '还没出结果。如果一直不动，可以点「停止生成」再试一次。';
}

export { waitingLabel, STAGE_QUICK, STAGE_LONG };
