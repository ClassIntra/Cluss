// 拼装最终 system prompt —— 拆成「恒定段」与「逐轮变化段」两部分
//
// ⚠️ 为什么要拆（这是本项目**最大的一笔计费优化**，务必先读懂再改）：
//
//   上游 KV 缓存是**前缀匹配**，而 messages 的顺序是 [system, ...历史..., 本轮user]。
//   system 只要有一个字节变了，它**后面的一切（包括整段历史）**都失配、都要按全价
//   price_in 重算。而改造前 system 的末尾挂着画像/记忆/余额/时间 —— 这四样每轮都在变，
//   于是历史**永远命中不了缓存**。
//
//   实测（cluss_usage_log 302 轮）：缓存命中率只有 10.2%（97,536 / 958,548），
//   而命中价 vs 输入价是 40 : 2000（默认模型）。把恒定段与变化段分开之后，
//   同一会话内 system 逐轮**逐字节一致**，历史才有机会命中。
//
//   返回 { stable, dynamic }：
//     stable  —— 同一会话内逐轮完全相同（BASE + 场景段 + 情感段 + 附件护栏），
//                作为真正的 system 消息。
//     dynamic —— 画像 / CI 素材 / 记忆 / 余额 / 时间。**不再进 system**，
//                由 turn-runner 拼到本轮用户消息的末尾（不落库）。
//
//   为什么不干脆把它们留在 system 的末尾：那样正是"每轮都变"的那个字节，
//   留着就等于把上面那笔优化全部白送给上游。
//
// ⚠️ 安全前提：dynamic 里含**从学生对话中提取的记忆**，位置从 system 换到 user 之后，
//   它在模型眼里从"系统说的"降级成"用户消息的一部分"——这**引入了提示注入面**。
//   所以 BASE 里有一条恒定声明（见 BASE 第 15 条）专门把这段背景块"重新授权"为
//   系统注入、不可伪造的内容。删掉那条声明会让本优化变成安全缺陷。
function getSystemPromptParts(opts) {
  var o = opts || {};
  var parts = [BASE];

  // 场景段
  // 笔记辅助自成一套：它既不套"分层引导解题"，也不是日常聊天，
  // 硬塞进任一场景都会让模型做出不合时宜的反应（比如整理笔记时反问"你先想想"）。
  if (o.mode === 'note') {
    parts.push(NOTE_ASSIST);
  } else if (o.mode === 'daily') {
    parts.push(DAILY);

    // 无限制风格段：紧跟 DAILY 之后、人格之前。
    //
    // 位置有讲究 —— 它是对 DAILY 第 5/6 条的**覆盖**，必须先让模型读到被覆盖的原文，
    // 再读到"那两条作废"。反过来（放在 DAILY 前面）模型会先建立"内容放开"的印象、
    // 再被 DAILY 的底线往回拽，实测表现是"放得犹豫"：给了半句又劝两句。
    // 该值随会话稳定，不破坏前缀缓存。
    if (o.dailyStyle === 'free') parts.push(DAILY_FREE);

    // 人格段跟在场景段后面：它按会话存储、整段稳定，不影响前缀缓存。
    // buddy（默认）没有附加文本，buildPersonaSection 返回 ''，自然跳过。
    // personaRecord 由调用方用 resolvePersona 解析好（内置从本模块取、自定义从库里取）。
    var personaSection = buildPersonaSection(o.personaRecord);
    if (personaSection) parts.push(personaSection);
  } else {
    var taskKind = o.taskKind;

    // ---- 作文：自成一套，不叠学习模式 ----
    // 作文要的是"写出一篇东西"或"按结构点评"，与"分层引导解题"是两套逻辑，
    // 叠在一起会让模型在批改作文时冒出"你先自己想想"这种不合时宜的话。
    if (taskKind === 'writing_generate' || taskKind === 'writing_grade' || taskKind === 'writing_outline') {
      var lang = o.writing && o.writing.language === 'en' ? 'en' : 'zh';

      if (taskKind === 'writing_generate') {
        parts.push(lang === 'en' ? WRITING_GEN_EN : WRITING_GEN_ZH);
      } else if (taskKind === 'writing_grade') {
        parts.push(WRITING_GRADE);
      } else {
        parts.push(WRITING_OUTLINE);
      }

      // 参数要求拼成一段明确指令
      parts.push(buildWritingParams(o.writing, lang));

      if (lang === 'en') parts.push(LANG_EN);
    } else {
      // ---- 解题链路 ----
      parts.push(o.studyStyle === 'direct' ? STUDY_DIRECT : STUDY_GUIDED);

      // 话题边界放宽：学习为中心，但接得住学习以外的时刻（对引导/直答都生效）
      parts.push(STUDY_SCOPE);

      if (taskKind === 'single') parts.push(SOLVE_SINGLE);
      else if (taskKind === 'multi') parts.push(SOLVE_MULTI);
      else if (taskKind === 'cross_page') parts.push(SOLVE_CROSS_PAGE);
      else if (taskKind === 'grade') parts.push(GRADE);
    }
  }

  // 情感与关系段：**所有场景**都注入，紧跟场景段之后。
  // 为什么放在附件段之前：附件段解决的是"这一轮带了资料该怎么处置"，
  // 而情感处理是更底层的一层（学生说「学不动了」时不该先被解题流程接管），
  // 应当先立住。内容恒定、不随会话变化，对上游前缀缓存友好。
  parts.push(EMOTION);

  // 附件段落只在真有附件时加，避免无附件对话被无关规则干扰。
  // 注：它随"本轮有没有附件"切换，所以它之后的字节（历史）在切换那一轮会失配。
  // 这是**可接受的**——同类会话里它通常稳定（拍题会话一直有、闲聊一直无），
  // 且它留在 system 里是安全需要（护栏不能跟着被护栏的内容一起进 user 消息）。
  if (o.hasAttachment) parts.push(ATTACHMENT_GUARD);

  // ===== 恒定段到此为止 =====
  var stable = parts.join('\n');

  // ---- 以下为**逐轮变化段**，一律不进 system（见 getSystemPromptParts 顶部说明）----
  var dyn = [];

  // notesReferenced：本轮是否注入了引用笔记的正文（o.noteText 非空）。
  // 画像里"你并不知道正文"那句要据此改口，否则与注入的正文自相矛盾，
  // 模型会声称看不到笔记 —— 见 buildProfileSection 里的说明。
  var profile = buildProfileSection(o.studentProfile, !!o.noteText);
  if (profile) dyn.push(profile);

  // ClassIntra 活动素材段：紧跟在画像之后。
  // 两者都是"关于这个学生的背景"，放一起便于模型整体理解。
  // 取不到时为 null → 直接跳过，不影响其它段落。
  var ciSection = buildCiSection(o.ciProfile);
  if (ciSection) dyn.push(ciSection);

  // 记忆段跟在画像后面：两者都是"关于这个学生的背景"，放一起便于模型整体理解。
  // 措辞里已声明"可能过时，以他现在说的为准"。
  var memorySection = memorySvc.buildMemorySection(o.memories);
  if (memorySection) dyn.push(memorySection);

  // 积分余额：只在学生主动问时用它回答，规则见 BASE 第 14 条。
  // 它每轮都在变（每轮扣费），所以必须落在变化段里。
  if (o.pointsBalance !== undefined && o.pointsBalance !== null) {
    var bal = '\n[积分余额] 当前可用 ' + Number(o.pointsBalance) + ' 积分';
    if (o.weeklyRemainingPoints !== undefined && o.weeklyRemainingPoints !== null) {
      bal += '；本周剩余 ' + Number(o.weeklyRemainingPoints) + ' 积分';
    }
    dyn.push(bal);
  }

  dyn.push('\n[当前时间] ' + time.nowLocalText());

  return { stable: stable, dynamic: dyn.join('\n') };
}

// 完整 system prompt（恒定段 + 变化段拼在一起）
//
// 保留这个入口是为了**向后兼容**：脚本与单测按"一个字符串"使用它。
// 生产链路（turn-runner）走 getSystemPromptParts，把两者分投到 system 与 user 消息，
// 以便让上游前缀缓存真正生效。
//
// 注意拼接口径与原实现**逐字节等价**：各段自身都以 '\n' 开头，
// 所以 stable + '\n' + dynamic 与过去把全部段一起 join('\n') 的结果相同。
function getSystemPrompt(opts) {
  var p = getSystemPromptParts(opts);
  return p.dynamic ? (p.stable + '\n' + p.dynamic) : p.stable;
}

// 把作文参数拼成一段明确的指令
// 空值不写进提示词——写"类型：（不限）"只会让模型困惑
function buildWritingParams(w, lang) {
  var p = w || {};
  var isEn = lang === 'en';
  var lines = ['', isEn ? '[Requirements]' : '【本次要求】'];

  var genre = String(p.genre || '').trim();
  var style = String(p.style || '').trim();
  var limit = Number(p.wordLimit || 0);
  var topic = String(p.topic || '').trim();

  if (topic) lines.push((isEn ? '- Topic: ' : '- 题目/要求：') + topic);
  if (genre) lines.push((isEn ? '- Genre: ' : '- 文体：') + genre);
  if (style) lines.push((isEn ? '- Style: ' : '- 风格：') + style);

  if (limit > 0) {
    lines.push(isEn
      ? ('- Length: about ' + limit + ' words')
      : ('- 字数：约 ' + limit + ' 字'));
  }

  if (lines.length === 1) {
    // 没有任何参数时也要给一句，否则模型不知道按什么写
    lines.push(isEn ? '- No specific requirements; use your judgement.' : '- 未指定具体要求，请你自行把握。');
  }

  return lines.join('\n');
}

// 任务指令前缀：拼接在用户输入之前
// 目的：让模型明确「这条消息的任务类型」，尤其是在同一会话里切换过模式之后
function getTaskHint(taskKind) {
  return TASK_HINTS[taskKind] || '';
}

// 跨页题需要告诉模型图片的顺序（否则它不知道哪张在前）
function buildCrossPageHint(imageCount) {
  if (!imageCount || imageCount < 2) return '';
  var labels = [];
  for (var i = 1; i <= imageCount; i++) labels.push('第' + i + '张');
  return '（本次共 ' + imageCount + ' 张图，按顺序为：' + labels.join(' → ') + '）';
}

