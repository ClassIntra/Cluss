// ---- 输出长度硬上限（max_tokens）----
//
// 为什么必须有这一层：**它是唯一能给"最坏情况"设上界的手段**。
// 实测（cluss_usage_log 302 轮真实流水）：
//   completion_tokens 分布极度长尾 —— 2.6% 的请求（8/302）吃掉了 16.6% 的总成本；
//   单轮最高 18431 token（14.9 积分），另一轮「你能帮我写一个人设吗」9623 token（8.78 积分）。
//   成本分位 p50 = 0.82 积分，p99 = 8.0 积分，max = 14.9 积分。
// 而在此之前**全链路没有任何 max_tokens** —— 模型跑飞时扣费是无上界的，
// 学生一次随口提问被扣近 9 分，这就是"扣费不可预期"最直接的来源。
//
// ⚠️ 定档原则：**只拦跑飞，不逼短**。
//   上限给到正常回答的 3 倍以上，正常回答永远碰不到它；只有模型失控（写成一篇
//   长文档 / 无限复读 / 把表格铺开）时才会被截断。任何"把上限压到正常回复附近"
//   的做法都会切掉答案，那个体验比多扣几分更糟。
//
// ⚠️ 作文与拍题必须给大档：它们的"长"是学生明确要求的（写 800 字作文、多题逐题作答），
//   拿对话档去限它们 = 系统性截断，属于功能损坏而不是省钱。
var OUTPUT_CAP = {
  chat: 3072,              // 日常 / 学习对话：正常回答多在一千以内，3072 是 3 倍余量
  solve: 4096,             // 拍题（单题 / 多题 / 跨页）：多题逐题作答可能真的很长
  grade: 4096,             // 作业批改：表格逐题一行
  note: 3072,              // 笔记辅助：整理/续写，同上
  writing_generate: 6144,  // 作文生成：学生可能要求上千字
  writing_grade: 4096,     // 作文批改：逐段点评 + 对照示例
  writing_outline: 3072    // 写作提纲：只给结构，不该长
};

// 上下文兜底上限：任何没被上面覆盖的组合都用它（模式值来自库里，可能是脏数据）
var OUTPUT_CAP_FALLBACK = 3072;

// 按场景取输出上限。纯函数，便于单测与在别处复用。
//
// 入参口径与 getSystemPrompt 一致（mode + taskKind）：
//   mode 'daily' | 'note' | 'study'
//   taskKind 'single'|'multi'|'cross_page'|'grade'|'writing_generate'|'writing_grade'|'writing_outline'
// 判据是**"这一轮的产出物本来该有多长"**，不是"我想让它多短"。
function outputCapFor(opts) {
  var o = opts || {};
  var mode = String(o.mode || '');
  var kind = String(o.taskKind || '');

  // 作文三兄弟优先：它们既可能在 study 链路也可能独立发起
  if (kind === 'writing_generate' || kind === 'writing_grade' || kind === 'writing_outline') {
    return OUTPUT_CAP[kind] || OUTPUT_CAP_FALLBACK;
  }
  // 拍题与批改（study 链路）
  if (kind === 'single' || kind === 'multi' || kind === 'cross_page') return OUTPUT_CAP.solve;
  if (kind === 'grade') return OUTPUT_CAP.grade;

  if (mode === 'note') return OUTPUT_CAP.note;
  return OUTPUT_CAP.chat;
}

