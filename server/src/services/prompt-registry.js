// 内置人格的 id 清单（数组顺序 = 前端展示顺序）
var PERSONA_ORDER = ['buddy', 'humor', 'cheer', 'calm'];

// 自定义人格的 id 前缀。
//
// 为什么带前缀而不是直接用数据库自增 id：内置人格的 id 是字符串（'humor'），
// 自定义人格若用裸数字，两套 id 体系混在一起就没有区分依据 ——
// 学生会遇到"自定义的 humor 把内置幽默顶掉了"这类身份混淆。
// 前缀让两套体系永不碰撞，排障时也能一眼看出这条人格来自哪里。
var CUSTOM_PERSONA_PREFIX = 'p:';

// 自定义人格 id 的形状：p:<数字>
function isCustomPersonaId(key) {
  var s = String(key || '');
  if (s.indexOf(CUSTOM_PERSONA_PREFIX) !== 0) return false;
  return /^\d+$/.test(s.slice(CUSTOM_PERSONA_PREFIX.length));
}

// 数据库主键 → 对外的人格 id（唯一生成点，避免各处自己拼前缀拼歪）
function customPersonaId(dbId) {
  return CUSTOM_PERSONA_PREFIX + Number(dbId);
}

// 非法值一律归为默认（空串），绝不抛错：
// 前端与服务端的人格定义可能不同步（服务端删过人格、或旧客户端缓存了它），
// 那种情况下学生该得到的是"语气回到默认"，而不是一个打不开的对话页。
//
// 自定义人格只做**形状校验**（是否形如 p:数字），刻意不查库：
//   1. 这个函数被 turn-runner 用于"写入前归一"，那时还没到渲染阶段，查库是多余 IO；
//   2. 人格被删掉后，渲染阶段的 resolvePersona 会取不到记录、自然回落到默认语气 ——
//      这正是我们要的降级，不必在这里就先否决它。
function normalizePersona(id) {
  var key = String(id || '').trim().toLowerCase();
  if (PERSONAS[key]) return key;
  if (isCustomPersonaId(key)) return key;
  return '';
}

// 日常风格归一：只有 'free' 是有效值，其余（含 ''）一律按默认「受限」处理。
// 与 normalizePersona 同策略 —— 不认识的值降级到默认，绝不抛错。
function normalizeDailyStyle(v) {
  return String(v || '').trim().toLowerCase() === 'free' ? 'free' : '';
}

// 内置人格清单。builtin 标记让前端能把"内置"与"我自建的"分组显示。
function listPersonas() {
  var out = [];
  for (var i = 0; i < PERSONA_ORDER.length; i++) {
    var id = PERSONA_ORDER[i];
    out.push({ id: id, label: PERSONAS[id].label, desc: PERSONAS[id].desc, builtin: 1 });
  }
  return out;
}

// 把「人格 id」解析成一条可渲染的人格记录
//
// customRecords: [{ id, name, prompt }] —— 调用方从库里取的**该学生自己的**人格
// 返回 { id, label, prompt, builtin } 或 null：
//   - 内置 id  → 从 PERSONAS 取
//   - p:数字   → 在 customRecords 里找；找不到返回 null（人格已被删 → 回落默认语气）
//
// 为什么 customRecords 由调用方传入、而不是自己查库：
//   prompt-registry 是纯函数模块（可单测、无副作用）。它一旦 require 数据库，
//   "提示词长什么样"就依赖运行时数据，测试与缓存都会变得不可预期。
function resolvePersona(id, customRecords) {
  var key = normalizePersona(id);
  if (!key) return null;

  if (PERSONAS[key]) {
    return { id: key, label: PERSONAS[key].label, prompt: PERSONAS[key].prompt, builtin: 1 };
  }

  var list = customRecords || [];
  for (var i = 0; i < list.length; i++) {
    if (list[i] && String(list[i].id) === key) {
      return {
        id: key,
        label: String(list[i].name || '自定义'),
        prompt: String(list[i].prompt || ''),
        builtin: 0
      };
    }
  }
  return null;
}

// 人格段：仅日常模式使用。rec 是 resolvePersona 的输出。
function buildPersonaSection(rec) {
  if (!rec || !rec.prompt) return '';
  var head = rec.builtin
    ? '【语气设定：' + rec.label + '】'
    : '【语气设定（学生自定义）：' + rec.label + '】';
  // 自定义人格要额外挂一层防线：学生写的文本不能获得系统指令的地位
  var guard = rec.builtin ? PERSONA_GUARD : (CUSTOM_PERSONA_GUARD + '\n\n' + PERSONA_GUARD);
  return ['', head, rec.prompt, '', guard].join('\n');
}

