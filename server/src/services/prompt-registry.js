// ---- 学生画像段 ----
// 放在 system prompt **末尾**（与时间一起），不能插在 BASE 之后：
// BASE 是上游 KV 缓存命中的前缀，画像会随学生的错题与会话不断变化，
// 插在前面会让缓存几乎每次都失效。
//
// 只陈述事实，不做评价：不写"该生数学较差"，只写"数学 5 道待复习"。
// 判断交给模型，避免系统替学生贴标签。
function buildProfileSection(p, notesReferenced) {
  if (!p) return '';

  var lines = [];

  var head = [];
  if (p.enrollYear) head.push(p.enrollYear + '级');
  if (p.classNo) head.push(p.classNo + '班');
  if (p.gender) head.push(p.gender);
  if (head.length) lines.push('- ' + head.join(' · '));

  if (p.weakSubjects && p.weakSubjects.length) {
    var subs = [];
    for (var i = 0; i < p.weakSubjects.length; i++) {
      subs.push(p.weakSubjects[i].subject + ' ' + p.weakSubjects[i].count + ' 道');
    }
    lines.push('- 错题本待复习：' + subs.join('、'));
  }

  if (p.commonReasons && p.commonReasons.length) {
    lines.push('- 常错类型：' + p.commonReasons.join('；'));
  }

  if (p.recentTopics && p.recentTopics.length) {
    lines.push('- 最近在问：' + p.recentTopics.join('、'));
  }

  // 笔记维度：他在主动整理什么。
  // 与"最近在问"分开列：问是提问（被动求解），记是整理（主动建构），
  // 讲解时切入点不同 —— 他记过的内容可以直接引用，不必从零讲。
  if (p.noteInsights) {
    var ni = p.noteInsights;
    if (ni.topTags && ni.topTags.length) {
      var tagParts = [];
      for (var t = 0; t < ni.topTags.length; t++) {
        tagParts.push(ni.topTags[t].tag + '（' + ni.topTags[t].count + ' 篇）');
      }
      lines.push('- 笔记分类：' + tagParts.join('、'));
    }
    if (ni.recentTitles && ni.recentTitles.length) {
      lines.push('- 最近在记：' + ni.recentTitles.join('、'));
    }
  }

  if (!lines.length) return '';

  return [
    '',
    '【关于这个学生】（系统根据他的使用记录整理，只用来帮你把握讲解深度与举例）',
    lines.join('\n'),
    '用法：当背景用。不要复述给他听，不要说"你某某科不好"，不要当成他已告诉你的信息。',
    '若他正在问的题正好落在「常错类型」里，讲这一类题时可以直接点明他上次栽在哪一步。',
    // ⚠️ 这段措辞必须区分「本轮有没有引用笔记」，两种情况给的话互相矛盾：
    //   未引用时说"你并不知道正文"是对的（防模型编造）；
    //   但本轮引用了笔记时，正文就注入在同一条消息的【我引用的笔记】里 ——
    //   两句话同时出现，模型按更保守的那条执行，学生会听到
    //   "我看不到你引用的笔记"（实测踩到：引用了笔记 AI 却说看不见）。
    notesReferenced
      ? '若他本轮引用了笔记（见这条消息末尾的【我引用的笔记】），那几篇的正文你**看得到**，' +
        '直接用，不要再说"看不到"。上面"只有标题与分类"只针对**没有**被引用的那部分笔记。'
      : '若他正在问的内容他已经记过笔记（见「最近在记 / 笔记分类」），可以直接沿用他自己整理的说法，' +
        '不必从零讲一遍 —— 但要注意：你只知道笔记的标题与分类，并不知道正文，' +
        '别编造笔记里的内容，需要时请他引用那篇笔记。'
  ].join('\n');
}

// ---- ClassIntra 活动素材段 ----
// 数据来自 ClassIntra 侧**脱敏后的只读接口**（个性签名 / 音乐口味 / 社区发帖与标签 /
// 棋类对局 / 等级与连续登录 / 学业倒计时）。Cluss 绝不直接读 CI 的库。
//
// 为什么与「关于这个学生」分成两段：来源与用法都不同 ——
//   那一段是他在 **Cluss 里的学习痕迹**（错题、笔记、提问）；
//   这一段是他在**校园社区里的活动**（发帖、听歌、下棋）。
// 混成一段，模型会把"他在社区很活跃"当成"他学习很努力"，那是两件事。
//
// ⚠️ 这一段的最后一句是整个模块里最要紧的一条：
//   一旦模型说出「我记得你在社区发过一条吐槽食堂的帖子」，
//   学生的第一反应是"它怎么知道"——那是被监视的感觉，不是被理解。
//   所以这些素材只用来**调整它怎么说话**，绝不用来**证明它知道什么**。
function buildCiSection(ci) {
  if (!ci) return '';

  var lines = [];

  if (ci.signature) lines.push('- 个性签名：「' + ci.signature + '」');

  // 等级 / 连续登录：参与度的粗略刻度，别当成能力评价
  var lv = ci.level || {};
  var lg = ci.login || {};
  var bits = [];
  if (lv.level) bits.push('校园社区等级 ' + lv.level);
  if (lg.streak) bits.push('连续登录 ' + lg.streak + ' 天');
  if (bits.length) lines.push('- ' + bits.join(' · '));

  // 音乐口味
  var music = ci.music || {};
  if (music.top_artists && music.top_artists.length) {
    var artists = [];
    for (var m = 0; m < music.top_artists.length; m++) {
      var ar = music.top_artists[m];
      if (!ar || !ar.name) continue;
      artists.push(ar.count > 1 ? (ar.name + '（' + ar.count + ' 首）') : ar.name);
    }
    if (artists.length) lines.push('- 常听的歌手/音乐人：' + artists.join('、'));
  }
  if (music.playlists && music.playlists.length) {
    lines.push('- 自建歌单：' + music.playlists.join('、'));
  }

  // 校园社区活动
  var com = ci.community || {};
  var cbits = [];
  if (com.post_count) cbits.push('发帖 ' + com.post_count + ' 篇');
  if (com.post_tags && com.post_tags.length) cbits.push('常用标签：' + com.post_tags.join('、'));
  if (com.likes_received) cbits.push('收到赞 ' + com.likes_received);
  if (cbits.length) lines.push('- 校园社区：' + cbits.join('；'));
  if (com.post_titles && com.post_titles.length) {
    lines.push('- 他公开发过的帖子：「' + com.post_titles.join('」「') + '」');
  }

  // 棋类
  var gm = ci.games || {};
  var gbits = [];
  if (gm.chess) gbits.push('国际象棋 ' + gm.chess + ' 局');
  if (gm.gomoku) gbits.push('五子棋 ' + gm.gomoku + ' 局');
  if (gbits.length) lines.push('- 棋类：' + gbits.join('、'));

  // 学业倒计时（CI 侧只放行 category='exam'）
  if (ci.exams && ci.exams.length) {
    var exams = [];
    for (var e = 0; e < ci.exams.length; e++) {
      if (ci.exams[e] && ci.exams[e].title) {
        exams.push(ci.exams[e].title + (ci.exams[e].target_date ? '（' + ci.exams[e].target_date + '）' : ''));
      }
    }
    if (exams.length) lines.push('- 他自己标的学业倒计时：' + exams.join('、'));
  }

  if (!lines.length) return '';

  return [
    '',
    '【他在校园社区里的活动】（来自学校系统，已脱敏；只用来判断兴趣与状态）',
    lines.join('\n'),
    '用法：当背景，只用来调整你的说话方式与举例方向（他是棋类爱好者，讲逻辑题时用棋局类比更好懂）。',
    '**绝对不要主动提起这些内容**：他不知道系统把这些告诉了 AI，一旦被说出来，',
    '他的感受是"被监视"而不是"被理解"。也不要用等级、连续登录天数去评价他（那是参与度）。',
    '可能过时：与他现在说的不一致时，以**他现在的说法**为准。'
  ].join('\n');
}

